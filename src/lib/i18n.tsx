export type TKey = keyof (typeof DICT)["ja"];

type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (k: TKey) => string;
  pick: (v: LText | undefined) => string;
};

const LocaleCtx = createContext<Ctx | null>(null);

export const LOCALE_KEY = "crossmania-locale";

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("ja");

  useEffect(() => {
    try {
      const stored = localStorage.getItem(LOCALE_KEY);
      if (stored === "en" || stored === "ja") setLocaleState(stored);
    } catch {
      /* ignore */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(LOCALE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<Ctx>(
    () => ({
      locale,
      setLocale,
      t: (k: TKey) => DICT[locale][k] ?? DICT.ja[k] ?? String(k),
      pick: (v: LText | undefined) => (v ? v[locale] : ""),
    }),
    [locale, setLocale],
  );

  return <LocaleCtx.Provider value={value}>{children}</LocaleCtx.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(LocaleCtx);
  if (!ctx) throw new Error("useI18n must be used inside LocaleProvider");
  return ctx;
}
